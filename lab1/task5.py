a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))
print("Сумма: ", a+b)
print("Разность: ", a-b)
print("Произведение: ", a*b)
if (b==0):
    print("На ноль делить нельзя")
else: 
    print("Частное: ", a/b)
    print("Остаток от деления: ", a%b)
print("Возведение в степень: ", a**b)